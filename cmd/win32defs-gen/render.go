type guidParts struct {
	Data1 uint32
	Data2 uint16
	Data3 uint16
	Data4 [8]byte
}

type generatedGUID struct {
	Identifier string
	Name       string
	Namespace  string
	Value      string
	Parts      guidParts
}

type generatedKey struct {
	Identifier string
	Parts      guidParts
	PropertyID uint32
}

const generatedHeader = "// Code generated by win32defs-gen; DO NOT EDIT.\n"

func specByName(name string) packageSpec {
	for _, spec := range packageSpecs {
		if spec.Name == name {
			return spec
		}
	}

	panic("unknown package specification " + name)
}

func renderConstants(spec packageSpec, constants []generatedConstant, methods []generatedConstantMethod, source sourceLock) ([]byte, error) {
	var output bytes.Buffer

	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "// Source: %s %s (%s).\n", source.Metadata.Package, source.Metadata.Version, source.Metadata.SHA256)
	fmt.Fprintf(&output, "// Documentation: %s %s (%s).\n\n", source.Documentation.Package, source.Documentation.Version, source.Documentation.SHA256)

	if spec.Declare {
		fmt.Fprintf(&output, "// Package %s provides %s\n", spec.Name, spec.Doc)
	}

	fmt.Fprintf(&output, "package %s\n\n", spec.Name)

	if spec.Declare {
		fmt.Fprintf(&output, "// %s is the common representation used by this package.\n", spec.TypeName)
		fmt.Fprintf(&output, "type %s %s\n\n", spec.TypeName, spec.Underlying)
	}

	output.WriteString("const (\n")
	for _, constant := range constants {
		writeGeneratedComment(&output, constant.Name, constant.Comment)
		fmt.Fprintf(&output, "\t%s %s = %s\n", constant.Name, constant.Type, constant.Expression)
	}
	output.WriteString(")\n")

	for _, method := range methods {
		writeGeneratedComment(&output, method.Name, method.Comment)
		fmt.Fprintf(&output, "func %s() uintptr {\n\treturn %s\n}\n\n", method.Name, method.Expression)
	}

	numeric := numericConstants(constants)
	if len(numeric) != 0 {
		renderLookup(&output, spec, numeric)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format package %s: %w", spec.Name, err)
	}

	return formatted, nil
}

func writeGeneratedComment(output *bytes.Buffer, name string, comment string) {
	comment = normalizeComment(comment)
	if comment == "" {
		return
	}

	lines := wrapComment(name+": "+comment, 116)
	for _, line := range lines {
		fmt.Fprintf(output, "\t// %s\n", line)
	}
}

func normalizeComment(comment string) string {
	return strings.Join(strings.Fields(stripHTML(comment)), " ")
}

func stripHTML(value string) string {
	var output strings.Builder
	inTag := false

	for _, character := range value {
		switch character {
		case '<':
			inTag = true
		case '>':
			if inTag {
				output.WriteByte(' ')
			}

			inTag = false
		default:
			if !inTag {
				output.WriteRune(character)
			}
		}
	}

	return html.UnescapeString(output.String())
}

func wrapComment(value string, width int) []string {
	words := strings.Fields(value)
	lines := make([]string, 0, 1)
	var line strings.Builder

	for _, word := range words {
		if line.Len() != 0 && line.Len()+1+len(word) > width {
			lines = append(lines, line.String())
			line.Reset()
		}

		if line.Len() != 0 {
			line.WriteByte(' ')
		}

		line.WriteString(word)
	}

	if line.Len() != 0 {
		lines = append(lines, line.String())
	}

	return lines
}

func numericConstants(constants []generatedConstant) []generatedConstant {
	result := make([]generatedConstant, 0, len(constants))
	for _, constant := range constants {
		if constant.Numeric {
			result = append(result, constant)
		}
	}

	return result
}

func renderLookup(output *bytes.Buffer, spec packageSpec, constants []generatedConstant) {
	byValue := make(map[string][]string)
	for _, constant := range constants {
		byValue[constant.LookupKey] = append(byValue[constant.LookupKey], constant.Name)
	}

	values := make([]string, 0, len(byValue))
	for value := range byValue {
		values = append(values, value)
		sort.Strings(byValue[value])
	}
	sort.Strings(values)

	fmt.Fprintf(output, "// Name returns the canonical symbolic name for value.\nfunc Name(value %s) (string, bool) {\n", spec.TypeName)
	output.WriteString("\tswitch value {\n")
	for _, value := range values {
		fmt.Fprintf(output, "\tcase %s(%s):\n\t\treturn %q, true\n", spec.TypeName, value, canonicalName(spec, byValue[value]))
	}
	output.WriteString("\tdefault:\n\t\treturn \"\", false\n\t}\n}\n\n")

	fmt.Fprintf(output, "// Names returns every symbolic alias for value in lexical order.\nfunc Names(value %s) []string {\n", spec.TypeName)
	output.WriteString("\tswitch value {\n")
	for _, value := range values {
		fmt.Fprintf(output, "\tcase %s(%s):\n\t\treturn []string{", spec.TypeName, value)
		for index, name := range byValue[value] {
			if index != 0 {
				output.WriteString(", ")
			}

			fmt.Fprintf(output, "%q", name)
		}
		output.WriteString("}\n")
	}
	output.WriteString("\tdefault:\n\t\treturn nil\n\t}\n}\n\n")

	fmt.Fprintf(output, "// Parse returns the numeric value associated with an exact symbolic name.\nfunc Parse(name string) (%s, bool) {\n", spec.TypeName)
	output.WriteString("\tswitch name {\n")
	for _, constant := range constants {
		fmt.Fprintf(output, "\tcase %q:\n\t\treturn %s, true\n", constant.Name, constant.Name)
	}
	output.WriteString("\tdefault:\n")
	fmt.Fprintf(output, "\t\treturn %s(0), false\n\t}\n}\n", spec.TypeName)
}

func canonicalRank(spec packageSpec, name string) int {
	if spec.CanonicalRank == nil {
		return 100
	}

	return spec.CanonicalRank(name)
}

func canonicalName(spec packageSpec, names []string) string {
	result := names[0]
	resultRank := canonicalRank(spec, result)

	for _, name := range names[1:] {
		rank := canonicalRank(spec, name)
		if rank < resultRank {
			result = name
			resultRank = rank
		}
	}

	return result
}

func collectGUIDs(items []metadataGUID) ([]generatedGUID, []collision, int) {
	byIdentifier := make(map[string][]generatedGUID)
	skipped := 0

	for _, item := range items {
		parts, err := parseGUID(item.Value)
		if err != nil {
			skipped++

			continue
		}

		prefix := "GUID_"
		switch item.Kind {
		case "interface":
			prefix = "IID_"
		case "class":
			prefix = "CLSID_"
		}

		candidate := generatedGUID{
			Identifier: sanitizeIdentifier(prefix + item.Name),
			Name:       item.Name,
			Namespace:  item.Namespace,
			Value:      strings.ToLower(item.Value),
			Parts:      parts,
		}
		byIdentifier[candidate.Identifier] = append(byIdentifier[candidate.Identifier], candidate)

		if item.Kind == "class" {
			legacy := candidate
			legacy.Identifier = sanitizeIdentifier("GUID_" + item.Name)
			byIdentifier[legacy.Identifier] = append(byIdentifier[legacy.Identifier], legacy)
		}
	}

	result := make([]generatedGUID, 0, len(items))
	collisions := make([]collision, 0)

	for identifier, definitions := range byIdentifier {
		byValue := make(map[string][]generatedGUID)
		for _, definition := range definitions {
			byValue[definition.Value] = append(byValue[definition.Value], definition)
		}

		if len(byValue) == 1 {
			result = append(result, definitions[0])

			continue
		}

		details := make([]string, 0, len(definitions))
		for _, definition := range definitions {
			details = append(details, definition.Namespace+"."+definition.Name+"="+definition.Value)

			qualified := sanitizeIdentifier(definition.Identifier + "_" + definition.Namespace)
			definition.Identifier = qualified
			result = append(result, definition)
		}
		sort.Strings(details)

		collisions = append(collisions, collision{Package: "guid", Name: identifier, Definitions: details})
	}

	sort.Slice(result, func(left int, right int) bool {
		return result[left].Identifier < result[right].Identifier
	})
	sort.Slice(collisions, func(left int, right int) bool {
		return collisions[left].Name < collisions[right].Name
	})

	return result, collisions, skipped
}

func renderGUIDs(items []generatedGUID, source sourceLock) ([]byte, error) {
	var output bytes.Buffer

	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "// Source: %s %s (%s).\n\n", source.Metadata.Package, source.Metadata.Version, source.Metadata.SHA256)
	output.WriteString("package guid\n\nvar (\n")

	for _, item := range items {
		fmt.Fprintf(&output, "\t%s = %s\n", item.Identifier, guidLiteral(item.Parts, ""))
	}
	output.WriteString(")\n\n")

	output.WriteString("// Lookup returns a GUID by its generated symbolic name.\n")
	output.WriteString("func Lookup(name string) (GUID, bool) {\n\tswitch name {\n")
	for _, item := range items {
		fmt.Fprintf(&output, "\tcase %q:\n\t\treturn %s, true\n", item.Identifier, item.Identifier)
	}
	output.WriteString("\tdefault:\n\t\treturn GUID{}, false\n\t}\n}\n\n")

	output.WriteString("// Name returns a canonical generated symbolic name for value.\n")
	output.WriteString("func Name(value GUID) (string, bool) {\n\tswitch value.Data1 {\n")
	byData1 := make(map[uint32][]generatedGUID)
	seen := make(map[string]struct{})
	for _, item := range items {
		if _, exists := seen[item.Value]; exists {
			continue
		}

		seen[item.Value] = struct{}{}
		byData1[item.Parts.Data1] = append(byData1[item.Parts.Data1], item)
	}

	data1Values := make([]uint32, 0, len(byData1))
	for data1 := range byData1 {
		data1Values = append(data1Values, data1)
	}
	sort.Slice(data1Values, func(left int, right int) bool {
		return data1Values[left] < data1Values[right]
	})

	for _, data1 := range data1Values {
		fmt.Fprintf(&output, "\tcase 0x%08X:\n\t\tswitch value {\n", data1)
		for _, item := range byData1[data1] {
			fmt.Fprintf(&output, "\t\tcase %s:\n\t\t\treturn %q, true\n", item.Identifier, item.Identifier)
		}
		output.WriteString("\t\t}\n")
	}
	output.WriteString("\t}\n\n\treturn \"\", false\n}\n")

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format GUID package: %w", err)
	}

	return formatted, nil
}

func collectKeys(items []metadataInitializer, managedType string) ([]generatedKey, int) {
	byName := make(map[string]generatedKey)
	skipped := 0

	for _, item := range items {
		if !strings.HasSuffix(item.ManagedType, managedType) {
			continue
		}

		parts, propertyID, err := parsePropertyKey(item.Value)
		if err != nil {
			skipped++

			continue
		}

		identifier := sanitizeIdentifier(item.Name)
		candidate := generatedKey{Identifier: identifier, Parts: parts, PropertyID: propertyID}
		if existing, exists := byName[identifier]; exists && existing != candidate {
			skipped++

			continue
		}

		byName[identifier] = candidate
	}

	result := make([]generatedKey, 0, len(byName))
	for _, item := range byName {
		result = append(result, item)
	}
	sort.Slice(result, func(left int, right int) bool {
		return result[left].Identifier < result[right].Identifier
	})

	return result, skipped
}

