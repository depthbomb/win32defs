func collectAuthorities(items []metadataInitializer) ([]generatedAuthority, int) {
	result := make([]generatedAuthority, 0)
	skipped := 0

	for _, item := range items {
		if !strings.HasSuffix(item.ManagedType, ".SID_IDENTIFIER_AUTHORITY") {
			continue
		}

		values, err := parseUnsignedList(item.Value, 6, 8)
		if err != nil {
			skipped++

			continue
		}

		authority := generatedAuthority{Name: sanitizeIdentifier(item.Name)}
		for index, value := range values {
			authority.Value[index] = byte(value)
		}

		result = append(result, authority)
	}

	sort.Slice(result, func(left int, right int) bool {
		return result[left].Name < result[right].Name
	})

	return result, skipped
}

func collectSyncInitializers(items []metadataInitializer) ([]generatedZeroInitializer, int) {
	result := make([]generatedZeroInitializer, 0)
	skipped := 0

	for _, item := range items {
		if !hasAnySuffix(item.ManagedType, ".CONDITION_VARIABLE", ".INIT_ONCE", ".SRWLOCK") {
			continue
		}

		if strings.TrimSpace(item.Value) != "0" {
			skipped++

			continue
		}

		result = append(result, generatedZeroInitializer{Name: sanitizeIdentifier(item.Name)})
	}

	sort.Slice(result, func(left int, right int) bool {
		return result[left].Name < result[right].Name
	})

	return result, skipped
}

