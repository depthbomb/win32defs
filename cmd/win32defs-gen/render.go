func renderCatalog(packages map[string][]generatedConstant, source sourceLock) ([]byte, error) {
	var output bytes.Buffer

	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "// Source: %s %s (%s).\n", source.Metadata.Package, source.Metadata.Version, source.Metadata.SHA256)
	fmt.Fprintf(&output, "// Documentation: %s %s (%s).\n\n", source.Documentation.Package, source.Documentation.Version, source.Documentation.SHA256)
	output.WriteString("package catalog\n\nimport \"iter\"\n\n")
	output.WriteString("var definitions = [...]Definition{\n")

	for _, spec := range packageSpecs {
		for _, constant := range packages[spec.Name] {
			commentField := catalogConstantFields(constant)

			fmt.Fprintf(
				&output,
				"\t{Package: %q, Name: %q, Value: %q, Namespace: %q, DeclaringType: %q, Documentation: %q%s},\n",
				spec.Name,
				constant.Name,
				constant.Expression,
				constant.Namespace,
				constant.DeclaringType,
				constant.Documentation,
				commentField,
			)
		}
	}

	output.WriteString("}\n\n")
	output.WriteString("// Lookup returns provenance and documentation for an exact package and symbol name.\n")
	output.WriteString("func Lookup(packageName string, name string) (Definition, bool) {\n")
	output.WriteString("\tswitch packageName {\n")

	for _, spec := range packageSpecs {
		constants := packages[spec.Name]
		if len(constants) == 0 {
			continue
		}

		fmt.Fprintf(&output, "\tcase %q:\n\t\tswitch name {\n", spec.Name)
		for _, constant := range constants {
			commentField := catalogConstantFields(constant)

			fmt.Fprintf(&output, "\t\tcase %q:\n", constant.Name)
			fmt.Fprintf(
				&output,
				"\t\t\treturn Definition{Package: %q, Name: %q, Value: %q, Namespace: %q, DeclaringType: %q, Documentation: %q%s}, true\n",
				spec.Name,
				constant.Name,
				constant.Expression,
				constant.Namespace,
				constant.DeclaringType,
				constant.Documentation,
				commentField,
			)
		}
		output.WriteString("\t\t}\n")
	}

	output.WriteString("\t}\n\n\treturn Definition{}, false\n}\n\n")
	output.WriteString("// Definitions iterates over every generated numeric and string definition.\n")
	output.WriteString("func Definitions() iter.Seq[Definition] {\n\treturn func(yield func(Definition) bool) {\n\t\tfor _, definition := range definitions {\n\t\t\tif !yield(definition) {\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n\t}\n}\n")

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format catalog package: %w", err)
	}

	return formatted, nil
}

func catalogConstantFields(constant generatedConstant) string {
	fields := catalogCommentField(constant.Comment)
	if constant.Family != "" {
		fields += fmt.Sprintf(", Family: %q, Flags: %t, Kind: %q", constant.Family, constant.Flags, constant.Kind)
	}

	return fields
}

func catalogCommentField(comment string) string {
	comment = normalizeComment(comment)
	if comment == "" {
		return ""
	}

	return fmt.Sprintf(", Comment: %q", comment)
}

func parseGUID(value string) (guidParts, error) {
	cleaned := strings.ReplaceAll(strings.TrimSpace(value), "-", "")
	if len(cleaned) != 32 {
		return guidParts{}, fmt.Errorf("invalid GUID %q", value)
	}

	data1, err := strconv.ParseUint(cleaned[0:8], 16, 32)
	if err != nil {
		return guidParts{}, err
	}

	data2, err := strconv.ParseUint(cleaned[8:12], 16, 16)
	if err != nil {
		return guidParts{}, err
	}

	data3, err := strconv.ParseUint(cleaned[12:16], 16, 16)
	if err != nil {
		return guidParts{}, err
	}

	result := guidParts{Data1: uint32(data1), Data2: uint16(data2), Data3: uint16(data3)}
	for index := range result.Data4 {
		byteValue, err := strconv.ParseUint(cleaned[16+index*2:18+index*2], 16, 8)
		if err != nil {
			return guidParts{}, err
		}

		result.Data4[index] = byte(byteValue)
	}

	return result, nil
}

func parsePropertyKey(value string) (guidParts, uint32, error) {
	values, err := parseUnsignedList(value, 12, 32)
	if err != nil {
		return guidParts{}, 0, fmt.Errorf("invalid property key %q", value)
	}

	parts := guidParts{Data1: uint32(values[0]), Data2: uint16(values[1]), Data3: uint16(values[2])}
	for index := range parts.Data4 {
		parts.Data4[index] = byte(values[index+3])
	}

	return parts, uint32(values[11]), nil
}

func parseUnsignedList(value string, count int, bitSize int) ([]uint64, error) {
	cleaned := strings.NewReplacer("{", "", "}", "", " ", "").Replace(value)
	pieces := strings.Split(cleaned, ",")
	if len(pieces) != count {
		return nil, fmt.Errorf("value %q has %d elements, want %d", value, len(pieces), count)
	}

	values := make([]uint64, len(pieces))
	for index, piece := range pieces {
		parsed, err := strconv.ParseUint(piece, 10, bitSize)
		if err != nil {
			return nil, err
		}

		values[index] = parsed
	}

	return values, nil
}

func guidLiteral(parts guidParts, qualifier string) string {
	return fmt.Sprintf(
		"%sGUID{Data1: 0x%08X, Data2: 0x%04X, Data3: 0x%04X, Data4: [8]byte{0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X}}",
		qualifier,
		parts.Data1,
		parts.Data2,
		parts.Data3,
		parts.Data4[0],
		parts.Data4[1],
		parts.Data4[2],
		parts.Data4[3],
		parts.Data4[4],
		parts.Data4[5],
		parts.Data4[6],
		parts.Data4[7],
	)
}

func sanitizeIdentifier(value string) string {
	var result strings.Builder

	for index, character := range value {
		valid := character == '_' || unicode.IsLetter(character) || (index > 0 && unicode.IsDigit(character))
		if valid {
			result.WriteRune(character)
		} else {
			result.WriteByte('_')
		}
	}

	return result.String()
}

func writeFormatted(path string, contents []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}

	if err := os.WriteFile(path, contents, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	return nil
}

func writeReport(path string, report generationReport) error {
	contents, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		return fmt.Errorf("encode generation report: %w", err)
	}

	contents = append(contents, '\n')

	return writeFormatted(path, contents)
}
